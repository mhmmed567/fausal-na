export type MessageKey = keyof typeof dict.ar;

type I18nValue = {
  locale: Locale;
  dir: "rtl" | "ltr";
  t: (key: MessageKey) => string;
  toggleLocale: () => void;
  categoryName: (en: string | null | undefined, ar: string | null | undefined) => string;
};

const I18nContext = createContext<I18nValue | null>(null);

export function I18nProvider({ children }: { children: ReactNode }) {
  const [locale, setLocale] = useState<Locale>(() => {
    const stored = localStorage.getItem("nahdha-locale");
    return stored === "en" ? "en" : "ar";
  });

  useEffect(() => {
    localStorage.setItem("nahdha-locale", locale);
    document.documentElement.lang = locale === "ar" ? "ar" : "en";
    document.documentElement.dir = locale === "ar" ? "rtl" : "ltr";
  }, [locale]);

  const value = useMemo<I18nValue>(
    () => ({
      locale,
      dir: locale === "ar" ? "rtl" : "ltr",
      t: (key) => dict[locale][key] ?? key,
      toggleLocale: () => setLocale((prev) => (prev === "ar" ? "en" : "ar")),
      categoryName: (en, ar) => {
        if (locale === "ar") return ar || en || "—";
        return en || ar || "—";
      },
    }),
    [locale],
  );

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n() {
  const ctx = useContext(I18nContext);
  if (!ctx) throw new Error("useI18n must be used within I18nProvider");
  return ctx;
}
